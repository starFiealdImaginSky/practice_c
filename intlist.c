#include <stdio.h>
#include <stdlib.h>

int main(void)
{
    int x[2] = {3, 2};
    int y[2];
    /* y = {3,2}; ←これはコンパイルエラー */
    y[0] = 3;
    y[1] = 2;
    int *z;
    /* z = 3; ←これは実行時エラー。理由は難しくなく、zはポインタ＝住所だから。 */
    /* *z = 3; ←これはSegmentation fault。プログラムが許可あされていないメモリ領域にアクセスしようとした際にOSから強制終了させられた。 */
    z = &x[0]; /* zにx[0]がいるアドレスを登録。このときのプリントはx[0]と同じ結果がでる。 */
    /* z = &x; ←これは実行時エラー。zに格納できるのは行き先がintのアドレスなのに、int[2]を格納しようとしたから。 */
    printf("%d", *z);
}